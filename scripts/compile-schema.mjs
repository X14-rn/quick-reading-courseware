// Generate the validator in Node, never through eval/new Function in the browser.
import Ajv2020 from 'ajv/dist/2020.js';
import standaloneCode from 'ajv/dist/standalone/index.js';
import { buildSync } from 'esbuild';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
const root=resolve(dirname(fileURLToPath(import.meta.url)), '..');
const schema=JSON.parse(readFileSync(resolve(root,'schemas/qr-courseware-map-1.1.schema.json'),'utf8'));
const ajv=new Ajv2020({allErrors:true,code:{source:true}});
const validate=ajv.compile(schema);
const result=buildSync({stdin:{contents:standaloneCode(ajv,validate),resolveDir:root,loader:'js'},
  bundle:true,format:'esm',platform:'browser',write:false,legalComments:'none'});
writeFileSync(resolve(root,'src/generated-validator.js'), '// Generated by scripts/compile-schema.mjs. Do not edit.\n'+result.outputFiles[0].text);
